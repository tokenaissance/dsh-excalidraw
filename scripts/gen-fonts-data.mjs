#!/usr/bin/env node
/**
 * Regenerate `src/fonts-data.mjs` from `fonts/MANIFEST.json`.
 *
 * The client half needs the family names, file names and unicode ranges to build
 * its `@font-face` rules; the host half reads the manifest itself. Keeping one
 * generated module (inlined into `client.js` by the build) means the two halves
 * cannot disagree.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'fonts/MANIFEST.json'), 'utf8'))
const fonts = Array.isArray(manifest.fonts) ? manifest.fonts : []
if (fonts.length === 0) throw new Error('fonts/MANIFEST.json lists no fonts')

const lines = [
  '// Generated by scripts/gen-fonts-data.mjs from fonts/MANIFEST.json — do not edit by hand.',
  'export const FONTS = [',
]
for (const font of fonts) {
  if (typeof font.family !== 'string' || typeof font.file !== 'string') {
    throw new Error(`manifest entry needs family + file: ${JSON.stringify(font)}`)
  }
  lines.push('  {')
  lines.push(`    family: ${JSON.stringify(font.family)},`)
  lines.push(`    file: ${JSON.stringify(font.file)},`)
  lines.push(`    weight: ${Number(font.weight) || 400},`)
  lines.push(`    style: ${JSON.stringify(font.style ?? 'normal')},`)
  if (typeof font.sha256 === 'string') lines.push(`    version: ${JSON.stringify(font.sha256.slice(0, 8))},`)
  if (font.unicodeRange) lines.push(`    unicodeRange: ${JSON.stringify(font.unicodeRange)},`)
  lines.push('  },')
}
lines.push(']', '')
const target = path.join(ROOT, 'src/fonts-data.mjs')
const next = lines.join('\n')
const check = process.argv.includes('--check')
if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== next) {
    console.error('src/fonts-data.mjs is out of date; run node scripts/gen-fonts-data.mjs')
    process.exit(1)
  }
  console.log(`src/fonts-data.mjs: up to date (${fonts.length} fonts)`)
} else {
  fs.writeFileSync(target, next)
  console.log(`src/fonts-data.mjs: ${fonts.length} fonts`)
}
